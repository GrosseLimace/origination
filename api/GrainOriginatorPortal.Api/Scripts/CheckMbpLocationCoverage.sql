-- Coverage over recent tickets (TicketBlDate cutoff bounds the ~2M-row scan; remove the
-- "AND TicketBlDate" line for an all-time check, which is slower).
;WITH t AS (
    SELECT
        LTRIM(RTRIM(ISNULL(OrganizationCode,''))) AS Org,
        LTRIM(RTRIM(ISNULL(ElevatorCode,'')))     AS Elev,
        CASE WHEN LEFT(LTRIM(ISNULL(ContractNumber,'')),1) IN ('U','L','C') THEN 'unapplied' ELSE 'applied' END AS Kind
    FROM base.vw_CurrentTickets
    WHERE TicketType IN ('U','P')
      AND (TicketStatusDescription IS NULL OR TicketStatusDescription <> 'Consolidated')
      AND ContractNumber IS NOT NULL
      AND TicketBlDate >= '2023-01-01'
      AND NULLIF(LTRIM(RTRIM(ISNULL(OrganizationCode,''))),'') IS NOT NULL
),
r AS (
    SELECT Kind, Org, Elev,
        CASE WHEN Elev <> '' AND EXISTS (SELECT 1 FROM #loc l WHERE l.LocationId = t.Org + '-' + t.Elev) THEN 1 ELSE 0 END AS HasComposite,
        CASE WHEN EXISTS (SELECT 1 FROM #loc l WHERE l.LocationId = t.Org) THEN 1 ELSE 0 END AS HasBareOrg
    FROM t
)
SELECT
    Kind,
    COUNT(*)                                                             AS TotalTickets,
    SUM(CASE WHEN Elev = '' THEN 1 ELSE 0 END)                           AS OrgOnlyTickets,
    SUM(HasComposite)                                                    AS ResolveComposite_Today,
    SUM(CASE WHEN HasComposite = 0 AND HasBareOrg = 1 THEN 1 ELSE 0 END) AS WouldResolve_BareOrgFallback,
    SUM(CASE WHEN HasComposite = 1 OR HasBareOrg = 1 THEN 0 ELSE 1 END)  AS BlankEvenWithFallback,
    SUM(CASE WHEN HasComposite = 1 THEN 0 ELSE 1 END)                    AS Blank_Today_CompositeOnly
FROM r
GROUP BY Kind
ORDER BY Kind;

