using System.ComponentModel.DataAnnotations;

namespace GrainOriginatorPortal.Mobile.Contracts;

// Limits mirror BinSiteRules / UpsertProducerDetailsRequest on the desktop surface. They are restated as
// literals (not referenced) because mobile contracts must not depend on Infrastructure types;
// MobileProducerDetailsPreservationTests pins them to the desktop values so the two cannot drift.

/// <summary>
/// Schema <c>ProducerDetails</c> (card #643). Carries every bin-site and grain-on-farm field, including the
/// ones the phone does not display (site key, coordinates, last bid), so a phone save can send the lists back
/// whole without erasing anything the desktop entered.
/// </summary>
public sealed record ProducerDetailsDto
{
    public required long CustomerId { get; init; }
    public decimal? TotalAcres { get; init; }
    /// <summary>Sum of the sites' capacities, null when no site records a capacity.</summary>
    public decimal? TotalBinCapacity { get; init; }
    public required IReadOnlyList<BinSiteDto> BinSites { get; init; }
    public required IReadOnlyList<GrainOnFarmItemDto> GrainOnFarm { get; init; }
    public string? ModifiedBy { get; init; }
    public DateTime? ModifiedAt { get; init; }
}

/// <summary>Schema <c>BinSite</c>. Used for reads and writes.</summary>
public sealed record BinSiteDto : IValidatableObject
{
    /// <summary>Stable key: echoed back for an existing site, generated by the phone for a new one. Grain rows
    /// link to their site through it. When absent the server generates one.</summary>
    public Guid? SiteKey { get; init; }

    [Required(AllowEmptyStrings = false, ErrorMessage = "Each bin site needs a name.")]
    [StringLength(MobileBinSiteLimits.NameMaxLength)]
    public required string Name { get; init; }

    [Range(0d, MobileBinSiteLimits.MaxCapacity, ErrorMessage = "Bin site capacity must be between 0 and 100,000,000 bushels.")]
    public decimal? Capacity { get; init; }

    [Range(MobileBinSiteLimits.MinLatitude, MobileBinSiteLimits.MaxLatitude,
        ErrorMessage = "Latitude must be between 7 and 84 (north of the equator, in North America).")]
    public decimal? Latitude { get; init; }

    [Range(MobileBinSiteLimits.MinLongitude, MobileBinSiteLimits.MaxLongitude,
        ErrorMessage = "Longitude must be negative (west), between -180 and -52, for North America.")]
    public decimal? Longitude { get; init; }

    public IEnumerable<ValidationResult> Validate(ValidationContext validationContext)
    {
        if (string.IsNullOrWhiteSpace(Name))
            yield return new ValidationResult("Each bin site needs a name.", [nameof(Name)]);
        if (Latitude.HasValue != Longitude.HasValue)
            yield return new ValidationResult("Give both latitude and longitude, or neither.",
                [Latitude.HasValue ? nameof(Longitude) : nameof(Latitude)]);
    }
}

/// <summary>Schema <c>GrainOnFarmItem</c>. Used for reads and writes; one row per commodity per site.</summary>
public sealed record GrainOnFarmItemDto
{
    /// <summary>The <see cref="BinSiteDto.SiteKey"/> this grain is stored at. Null, or a key matching no
    /// site in the same save, stores the row without a site.</summary>
    public Guid? BinSiteKey { get; init; }

    /// <summary>The site's name, for display. Ignored on write.</summary>
    [StringLength(MobileBinSiteLimits.NameMaxLength)]
    public string? BinSiteName { get; init; }

    [Required(AllowEmptyStrings = false)]
    [StringLength(100)]
    public required string CommodityCode { get; init; }

    [Range(0d, 1_000_000_000d)]
    public decimal? BushelsOnHand { get; init; }

    [Range(0d, 1_000_000_000d)]
    public decimal? BushelsSold { get; init; }

    /// <summary>$/bu target price (the desktop's "Target"); may be negative for a basis target.</summary>
    [Range(-1_000_000_000d, 1_000_000_000d)]
    public decimal? TargetBushels { get; init; }

    /// <summary>Last bid entered by the user; may be negative for a basis bid.</summary>
    [Range(-1_000_000_000d, 1_000_000_000d)]
    public decimal? LastBid { get; init; }

    [StringLength(100)]
    public string? Grade { get; init; }
}

/// <summary>Schema <c>ContactUpdate</c>: one entered contact, the desktop's <c>ContactItemRequest</c> rules.</summary>
public sealed record ContactUpdateDto : IValidatableObject
{
    [Required(AllowEmptyStrings = false, ErrorMessage = "Each contact needs a name.")]
    [StringLength(200)]
    public required string Name { get; init; }

    [StringLength(50)]
    public string? Phone { get; init; }

    [StringLength(255)]
    [EmailAddress]
    public string? Email { get; init; }

    /// <summary>At most one should be flagged; the server keeps exactly one (first wins, else the first row).</summary>
    public bool IsPrimary { get; init; }

    public IEnumerable<ValidationResult> Validate(ValidationContext validationContext)
    {
        if (string.IsNullOrWhiteSpace(Name))
            yield return new ValidationResult("Each contact needs a name.", [nameof(Name)]);
    }
}

/// <summary>
/// Schema <c>ProducerDetailsUpdate</c>. Same contract as the desktop save: a list that is present REPLACES
/// the stored set (array order = display order); a list that is absent PRESERVES it. That holds for bin sites,
/// grain on farm and (since 2026-10-14) contacts. <see cref="TotalAcres"/> is always written, so a client must
/// send the current value when it is not changing it. <see cref="ExpectedModifiedAt"/> turns a concurrent
/// desktop edit into a 409 instead of a silent overwrite.
/// </summary>
public sealed record ProducerDetailsUpdateRequest
{
    [Required]
    public required Guid ClientRequestId { get; init; }

    [Range(0, 10_000_000)]
    public decimal? TotalAcres { get; init; }

    [MaxLength(MobileBinSiteLimits.MaxPerCustomer, ErrorMessage = "A producer can have at most 100 bin sites.")]
    public IReadOnlyList<BinSiteDto>? BinSites { get; init; }

    [MaxLength(2000)]
    public IReadOnlyList<GrainOnFarmItemDto>? GrainOnFarm { get; init; }

    /// <summary>Entered contacts, primary first (array order = display order). Absent = keep the stored ones.</summary>
    [MaxLength(50)]
    public IReadOnlyList<ContactUpdateDto>? Contacts { get; init; }

    /// <summary>Optimistic concurrency: the <c>modifiedAt</c> the client last read; 409 when it no longer matches.</summary>
    public DateTime? ExpectedModifiedAt { get; init; }
}

/// <summary>The desktop's <c>BinSiteRules</c>, restated for the mobile contract (see the file header).</summary>
public static class MobileBinSiteLimits
{
    public const int MaxPerCustomer = 100;
    public const int NameMaxLength = 100;
    public const double MinLatitude = 7.0;
    public const double MaxLatitude = 84.0;
    public const double MinLongitude = -180.0;
    public const double MaxLongitude = -52.0;
    public const double MaxCapacity = 100_000_000;
}
